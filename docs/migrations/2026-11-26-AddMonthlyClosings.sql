CREATE TABLE monthly_closings (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    month date NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (now()),
    created_by character varying(100),
    row_version integer NOT NULL,
    updated_at timestamp with time zone NOT NULL DEFAULT (now()),
    updated_by character varying(100),
    CONSTRAINT "PK_monthly_closings" PRIMARY KEY (id),
    CONSTRAINT ck_monthly_closings_first_day CHECK (extract(day FROM month) = 1)
);

CREATE TABLE receivable_balances (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    billing_customer_id bigint NOT NULL,
    opening numeric(15,0) NOT NULL,
    sales numeric(15,0) NOT NULL,
    tax numeric(15,0) NOT NULL,
    received numeric(15,0) NOT NULL,
    closing numeric(15,0) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (now()),
    created_by character varying(100),
    monthly_closing_id bigint NOT NULL,
    row_version integer NOT NULL,
    updated_at timestamp with time zone NOT NULL DEFAULT (now()),
    updated_by character varying(100),
    CONSTRAINT "PK_receivable_balances" PRIMARY KEY (id),
    CONSTRAINT ck_receivable_balances_closing CHECK (closing = opening + sales + tax - received),
    CONSTRAINT "FK_receivable_balances_customers_billing_customer_id" FOREIGN KEY (billing_customer_id) REFERENCES customers (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_receivable_balances_monthly_closings_monthly_closing_id" FOREIGN KEY (monthly_closing_id) REFERENCES monthly_closings (id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX "IX_monthly_closings_month" ON monthly_closings (month);

CREATE INDEX "IX_receivable_balances_billing_customer_id" ON receivable_balances (billing_customer_id);

CREATE UNIQUE INDEX "IX_receivable_balances_monthly_closing_id_billing_customer_id" ON receivable_balances (monthly_closing_id, billing_customer_id);

CREATE FUNCTION reject_closed_month() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    target date := (to_jsonb(NEW) ->> TG_ARGV[0])::date;
    closed date := (SELECT max(month) FROM monthly_closings);
BEGIN
    IF closed IS NOT NULL AND target < (closed + interval '1 month')::date THEN
        RAISE EXCEPTION '%.% % は、月次締めした % 以前の日付', TG_TABLE_NAME, TG_ARGV[0], target, to_char(closed, 'YYYY-MM')
            USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_closed_month', TABLE = TG_TABLE_NAME;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER tr_sales_records_closed_month BEFORE INSERT ON sales_records FOR EACH ROW EXECUTE FUNCTION reject_closed_month('recorded_on');
CREATE TRIGGER tr_receipts_closed_month BEFORE INSERT ON receipts FOR EACH ROW EXECUTE FUNCTION reject_closed_month('received_on');
CREATE TRIGGER tr_invoices_closed_month BEFORE INSERT ON invoices FOR EACH ROW EXECUTE FUNCTION reject_closed_month('closing_date');

