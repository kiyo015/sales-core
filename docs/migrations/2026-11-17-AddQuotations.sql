CREATE SEQUENCE quotation_number_seq START WITH 1 INCREMENT BY 1 NO MINVALUE MAXVALUE 999999 NO CYCLE;

CREATE TABLE quotations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    customer_id bigint NOT NULL,
    quoted_on date NOT NULL,
    valid_until date NOT NULL,
    status character varying(20) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (now()),
    created_by character varying(100),
    number character varying(20) NOT NULL DEFAULT ('QT-' || lpad(nextval('quotation_number_seq')::text, 6, '0')),
    row_version integer NOT NULL,
    updated_at timestamp with time zone NOT NULL DEFAULT (now()),
    updated_by character varying(100),
    CONSTRAINT "PK_quotations" PRIMARY KEY (id),
    CONSTRAINT ck_quotations_valid_period CHECK (valid_until >= quoted_on),
    CONSTRAINT "FK_quotations_customers_customer_id" FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT
);

CREATE TABLE quotation_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    quantity numeric(15,3) NOT NULL,
    unit_price numeric(15,2) NOT NULL,
    tax_rate numeric(5,2) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (now()),
    created_by character varying(100),
    product_id bigint NOT NULL,
    quotation_id bigint NOT NULL,
    row_version integer NOT NULL,
    updated_at timestamp with time zone NOT NULL DEFAULT (now()),
    updated_by character varying(100),
    CONSTRAINT "PK_quotation_lines" PRIMARY KEY (id),
    CONSTRAINT "FK_quotation_lines_products_product_id" FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_quotation_lines_quotations_quotation_id" FOREIGN KEY (quotation_id) REFERENCES quotations (id) ON DELETE RESTRICT
);

CREATE INDEX "IX_quotation_lines_product_id" ON quotation_lines (product_id);

CREATE INDEX "IX_quotation_lines_quotation_id" ON quotation_lines (quotation_id);

CREATE INDEX "IX_quotations_customer_id" ON quotations (customer_id);

CREATE UNIQUE INDEX "IX_quotations_number" ON quotations (number);

